"""Inbox markdown export.

After every feedback create / archive / dismiss, this regenerates a
user-scoped mirror at data/feedback/users/<digest>/inbox.md and archive.md.
The digest is the full SHA-256 of the UTF-8 user ID. Existing global mirrors
are legacy files and are neither overwritten nor removed.
"""

from __future__ import annotations

from hashlib import sha256
from pathlib import Path
import logging

from ..repositories import FeedbackRepository


def regenerate_inbox(repo: FeedbackRepository, user_id: str, repo_root: Path) -> None:
    # The database write has already succeeded. An optional filesystem mirror
    # must not turn that success into a 500 that invites duplicate submissions.
    try:
        _write_inbox(repo, user_id, repo_root)
    except Exception:
        logging.getLogger(__name__).warning("Feedback markdown mirror unavailable; database rows remain saved", exc_info=True)


def _write_inbox(repo: FeedbackRepository, user_id: str, repo_root: Path) -> None:
    # Keep user exports separate without allowing IDs to become path syntax.
    user_digest = sha256(user_id.encode("utf-8")).hexdigest()
    out_dir = repo_root / "data" / "feedback" / "users" / user_digest
    out_dir.mkdir(parents=True, exist_ok=True)
    inbox = out_dir / "inbox.md"
    archive = out_dir / "archive.md"

    open_items = repo.list_for_user(user_id, status="open")
    backlog = repo.list_for_user(user_id, status="backlog", limit=50)
    archived = repo.list_for_user(user_id, status="archived", limit=50)
    dismissed = repo.list_for_user(user_id, status="dismissed", limit=20)

    lines: list[str] = []
    lines.append("# Feedback inbox")
    lines.append("")
    lines.append(
        f"_Open: {len(open_items)} · Backlog: {len(backlog)} · "
        f"Closed (archived/dismissed): {len(archived)}/{len(dismissed)}. "
        f"Generated by `feedback_inbox.regenerate_inbox`._"
    )
    lines.append("")
    lines.append("Status semantics (GitHub-style): **open** = needs triage, **backlog** = acknowledged + deferred, **closed** = handled or dismissed. Only open items appear below — read backlog/closed via the web UI at `/feedback/inbox`.")
    lines.append("")
    if not open_items:
        lines.append("_Nothing open. Inbox zero._")
        lines.append("")
    if backlog:
        lines.append(f"### Backlog (deferred · {len(backlog)})")
        lines.append("")
        for fb in backlog:
            ts = fb.created_at.strftime("%Y-%m-%d")
            note = f" — _{fb.processing_notes}_" if fb.processing_notes else ""
            lines.append(f"- **#{fb.id}** ({ts}) `{fb.url}` — {fb.body[:160]}{note}")
        lines.append("")
    for fb in open_items:
        lines.append(f"## #{fb.id} · {fb.created_at.strftime('%Y-%m-%d %H:%M UTC')}")
        lines.append("")
        lines.append(f"- **URL:** `{fb.url}`")
        if fb.page_title:
            lines.append(f"- **Title:** {fb.page_title}")
        meta = []
        if fb.theme:
            meta.append(f"theme `{fb.theme}`")
        if fb.viewport_width:
            meta.append(f"viewport `{fb.viewport_width}px`")
        if meta:
            lines.append(f"- **Context:** {', '.join(meta)}")
        lines.append("")
        lines.append("> " + fb.body.replace("\n", "\n> "))
        lines.append("")
    inbox.write_text("\n".join(lines))

    # Archive markdown — a rolling log so the user (or me) can see what's
    # been processed.
    arc_lines: list[str] = ["# Feedback archive", ""]
    if not archived and not dismissed:
        arc_lines.append("_Empty._")
    for label, group in [("Archived (handled)", archived), ("Dismissed", dismissed)]:
        if not group:
            continue
        arc_lines.append(f"## {label}")
        arc_lines.append("")
        for fb in group:
            ts = (fb.processed_at or fb.created_at).strftime("%Y-%m-%d %H:%M")
            arc_lines.append(f"- **#{fb.id}** ({ts}) `{fb.url}` — {fb.body[:200]}")
            if fb.processing_notes:
                arc_lines.append(f"  - note: {fb.processing_notes}")
        arc_lines.append("")
    archive.write_text("\n".join(arc_lines))
